/*
1. 取引金額設定の状況
現在のシステムでは、固定の金額をベースに毎回のエントリーロット数を動的に算出する仕組みになっています。
 1回あたりの基準取引額: 400,000円 (`TARGET_TRADE_AMOUNT`)
 ロット算出式: 400,000円 ÷ 現在の通貨価格 （※小数点以下4桁に丸めて算出）
---
2. 共通で適用されるルール
すべての戦略において、実行している時間足（TimeFrame）に応じた「固定パーセンテージでの利確（TP）と損切り（SL）」がベースの決済ルールとして常時稼働しています。
 1分足: ±0.15%
 5分足: ±0.3%
 15分足: ±0.5%
 30分足: ±0.8%
 1時間足: ±1.0%
 4時間足: ±2.0%
 日足: ±5.0%
---
 3. 戦略ごとの具体的な強制ルール
共通ルールのパーセンテージに到達する前に、各戦略固有の条件を満たした場合に発動する強制決済ルールです。
 
 金額ベースの強制損切り（セーフティネット）
 【戦略92, 93, 94】: 含み損が -6,000円 に達した時点で強制決済。
 【戦略10】: 含み損が -5,000円 に達した時点で強制決済。
 
 テクニカル指標（MA5）を基準とした決済
 【戦略9, 92】: 確定足でMA5を抜けたらドテン決済（ロング保有時は下抜け、ショート保有時は上抜け）。
 【戦略93, 94】: 確定足でMA5を抜けたら逆張りのドテン決済（ロング保有時は上抜け、ショート保有時は下抜け）。
 【戦略3, 32】: MA5ラインに対して 0.2% のバッファ（ゆとり）を加味した上での抜けで決済。
 
 時間経過による強制決済（タイムリミット）
 【戦略10】: 次足の終値のタイミング（ローソク足1本分経過）で強制決済。
 【戦略5, 6, 52, 62】: エントリーから 2本目 のローソク足のタイミングで強制決済（※コード上、このルールはショートポジションのみに設定されています）。
 【戦略2, 4, 42】: エントリーから 3本目 のローソク足のタイミングで強制決済。
 
 条件付きの時間経過決済
 【戦略22】: エントリーから 2本目 のタイミングで、相場が逆行する足（ロング保有時に陰線、ショート保有時に陽線）が確定していた場合、次足の終値で決済。

 */
	
    public static void main(String[] args) {
        SpringApplication.run(CryptoToolApplication.class, args);
    }
